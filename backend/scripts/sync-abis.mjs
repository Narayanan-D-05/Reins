// Copies ABIs straight out of Foundry's build artifacts into
// src/chain/abis.generated.ts, so the backend's ABIs can never drift from
// what's actually deployed. Run after `forge build` in ../contracts.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const contractsOut = join(__dirname, "..", "..", "contracts", "out");

const targets = [
  { file: "ReinsAccount.sol/ReinsAccount.json", export: "ReinsAccountAbi" },
  { file: "ReceiptBook.sol/ReceiptBook.json", export: "ReceiptBookAbi" },
  { file: "Attestor.sol/Attestor.json", export: "AttestorAbi" },
  { file: "SettlementGate.sol/SettlementGate.json", export: "SettlementGateAbi" },
  { file: "ReinsAccountFactory.sol/ReinsAccountFactory.json", export: "ReinsAccountFactoryAbi" },
  { file: "IERC8004IdentityRegistry.sol/IERC8004IdentityRegistry.json", export: "ERC8004IdentityRegistryAbi" },
];

let output = "// AUTO-GENERATED by scripts/sync-abis.mjs — do not edit by hand.\n";
output += "// Run `npm run sync-abis` after `forge build` in ../contracts to refresh.\n\n";

for (const { file, export: exportName } of targets) {
  const path = join(contractsOut, file);
  if (!existsSync(path)) {
    throw new Error(`Missing build artifact: ${path}. Run "forge build" in contracts/ first.`);
  }
  const json = JSON.parse(readFileSync(path, "utf-8"));
  output += `export const ${exportName} = ${JSON.stringify(json.abi, null, 2)} as const;\n\n`;
}

const outPath = join(__dirname, "..", "src", "chain", "abis.generated.ts");
writeFileSync(outPath, output);
console.log(`Wrote ${targets.length} ABIs to ${outPath}`);
